// @ts-nocheck — this is the wrangler entry, not part of the Next app. It
// statically imports `../.open-next/worker.js`, which OpenNext only emits
// during `opennextjs-cloudflare build` (after `next build`). That module
// therefore can't exist at type-check time, so type-checking this glue
// file is impossible by construction; wrangler resolves the import at
// bundle time, once the file has been generated.
/**
 * @packageDocumentation
 *
 * Production Worker entry point.
 *
 * Cloudflare's Workflows runtime looks for Workflow classes as named
 * exports on the deployed Worker. The Next.js handler is generated by
 * OpenNext into `.open-next/worker.js` — this file re-exports the
 * Workflow classes alongside that generated handler, and adds the
 * `scheduled()` handler that cron triggers fire into.
 *
 * Deployment glue:
 *
 *   1. `wrangler.jsonc` -> `main` set to this file (`src/worker.ts`).
 *   2. `next build && opennextjs-cloudflare build` produces
 *      `.open-next/worker.js`.
 *   3. `wrangler deploy` bundles this file, which composes the OpenNext
 *      fetch handler with our scheduled handler and Workflow classes.
 */

import openNextHandler from '../.open-next/worker.js';

export { ScrapeWorkflow, MovieWorkflow } from './workflows/index';

const handler: ExportedHandler<CloudflareEnv> = {
  /** Forwarded straight to OpenNext's Next.js handler. */
  fetch(request, env, ctx) {
    return (openNextHandler as ExportedHandler<CloudflareEnv>).fetch!(
      request,
      env,
      ctx,
    );
  },

  /**
   * Cron-trigger entrypoint. The daily tick kicks off a single
   * ScrapeWorkflow, which scrapes the sources and then dispatches one
   * MovieWorkflow per newly-seen movie. Each MovieWorkflow owns the
   * whole lifecycle of its one movie (enrich → sleep 24h → torrent), so
   * no single instance comes anywhere near the per-invocation subrequest
   * cap regardless of how many movies arrive.
   */
  async scheduled(_event, env, ctx) {
    const safeCreate = async (
      label: string,
      workflow: Workflow | undefined,
      params: unknown,
    ): Promise<void> => {
      if (!workflow) {
        return;
      }
      try {
        const instance = await workflow.create({ params });
        const payload = {
          event: 'workflow.created',
          workflow: label,
          instanceId: instance.id,
          ts: new Date().toISOString(),
        };
        console.log(JSON.stringify(payload));
      } catch (err) {
        // Workflow create may transiently fail (rate limit, local-dev
        // simulator gaps). Log and move on so one bad fan-out doesn't
        // sink the entire scheduled tick.
        const payload = {
          event: 'workflow.create.failed',
          workflow: label,
          error: err instanceof Error ? err.message : String(err),
          ts: new Date().toISOString(),
        };
        console.error(JSON.stringify(payload));
      }
    };
    ctx.waitUntil(
      safeCreate('scrape', env.SCRAPE_WORKFLOW, { pageNumbers: [1] }),
    );
  },
};

export default handler;
